import Foundation
import FirebaseFunctions

/// Thin client for the 13 Cloud Functions in /functions.
/// Matches com.example.data.backend.BackendApi.kt 1:1.
/// Target Region: asia-south1
public class BackendApi {
    public static let shared = BackendApi()

    private lazy var functions: Functions = {
        return Functions.functions(region: "asia-south1")
    }()

    private func call(name: String, data: [String: Any]) async throws -> [String: Any] {
        let callable = functions.httpsCallable(name)
        let result = try await callable.call(data)
        guard let dict = result.data as? [String: Any] else {
            return [:]
        }
        return dict
    }

    // 1. Send Email OTP for registration / owner password reset
    public func sendEmailOtp(email: String, purpose: String) async throws -> [String: Any] {
        return try await call(name: "sendEmailOtp", data: ["email": email, "purpose": purpose])
    }

    // 2. Verify Email OTP and obtain short-lived verificationToken
    public func verifyEmailOtp(email: String, purpose: String, code: String) async throws -> String {
        let res = try await call(name: "verifyEmailOtp", data: ["email": email, "purpose": purpose, "code": code])
        guard let token = res["verificationToken"] as? String else {
            throw NSError(domain: "TaskFlowBackend", code: -1, userInfo: [NSLocalizedDescriptionKey: "OTP Verification failed: No token returned"])
        }
        return token
    }

    // 3. Register Company (Atomic organization, auth user, admin claims creation)
    public func registerCompany(fields: [String: Any]) async throws -> [String: Any] {
        return try await call(name: "registerCompany", data: fields)
    }

    // 4. Create Member (Privileged staff/manager account creation with auto Employee ID)
    public func createMember(name: String, role: String, phone: String, departmentId: String, departmentName: String, contactEmail: String) async throws -> [String: Any] {
        return try await call(name: "createMember", data: [
            "name": name,
            "role": role,
            "phone": phone,
            "departmentId": departmentId,
            "departmentName": departmentName,
            "contactEmail": contactEmail
        ])
    }

    // 5. Deactivate Member
    public func deactivateMember(memberId: String) async throws -> [String: Any] {
        return try await call(name: "deactivateMember", data: ["memberId": memberId])
    }

    // 6. Decide Approval (Admin approves/rejects manager permission request)
    public func decideApproval(requestId: String, approve: Bool, notes: String) async throws -> [String: Any] {
        return try await call(name: "decideApproval", data: [
            "requestId": requestId,
            "decision": approve ? "approve" : "reject",
            "notes": notes
        ])
    }

    // 7. Request Password Recovery
    public func requestPasswordRecovery(employeeId: String) async throws -> [String: Any] {
        return try await call(name: "requestRecovery", data: ["kind": "password", "employeeId": employeeId])
    }

    // 8. Request ID Recovery
    public func requestIdRecovery(fullName: String, companyEmail: String) async throws -> [String: Any] {
        return try await call(name: "requestRecovery", data: ["kind": "id", "fullName": fullName, "companyEmail": companyEmail])
    }

    // 9. Decide Recovery Request
    public func decideRecovery(requestId: String, approve: Bool) async throws -> [String: Any] {
        return try await call(name: "decideRecovery", data: ["requestId": requestId, "decision": approve ? "approve" : "reject"])
    }

    // 10. Owner Reset Password
    public func ownerResetPassword(email: String, verificationToken: String, newPassword: String) async throws -> [String: Any] {
        return try await call(name: "ownerResetPassword", data: [
            "email": email,
            "verificationToken": verificationToken,
            "newPassword": newPassword
        ])
    }

    // 11. Register FCM Push Notification Token
    public func registerFcmToken(token: String) async throws -> [String: Any] {
        return try await call(name: "registerFcmToken", data: ["token": token])
    }

    // 12. Complete First Login Password Change
    public func completePasswordChange() async throws -> [String: Any] {
        return try await call(name: "completePasswordChange", data: [:])
    }

    // 13. AI Assist (Google Gemini 2.5 Flash via Secure Backend)
    public func aiAssist(question: String) async throws -> String {
        let res = try await call(name: "aiAssist", data: ["question": question])
        return res["answer"] as? String ?? "No response generated by AI assistant."
    }
}
